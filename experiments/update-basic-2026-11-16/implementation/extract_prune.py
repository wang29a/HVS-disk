"""Extract only the proven DEG selector and its unchanged range helpers."""
from pathlib import Path
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parent.parent
E = Path('/mnt/nvme3/wz/hvs-disk-build-20261027/experiments')
AB = E/'backlink-ab-20261115/runtime'


def sha(b):
    return hashlib.sha256(b).hexdigest()


def body(text, needle):
    start = text.index(needle)
    begin = text.index('{', start)
    end, depth = begin+1, 1
    while depth:
        depth += (text[end] == '{') - (text[end] == '}')
        end += 1
    return text[begin:end]


def main():
    proof = json.loads((AB/'validation/build.json').read_text())
    source = AB/'build/hybrid_index.cpp'
    raw = source.read_bytes()
    assert sha(raw) == proof['variant'], 'verified selector identity changed'
    gate = json.loads((AB/'function-v2/validation/function-gate.json').read_text())
    assert gate['status'] == 'PASS' and gate['cases'] == 10000
    text = raw.decode()
    selector = body(text, '::prune_neighbors_no_opt(')
    assert selector.count('picked.size() < range') >= 2
    # Remove only legacy-comparison counters. They cannot change selected IDs,
    # distances, layers or intervals. This makes the library independent of the
    # experimental stats registry and its lifetime/concurrency assumptions.
    selector = selector.replace('  const unsigned range = parameter.Get<unsigned>("R");\n', '')
    selector = selector.replace('      std::vector<std::pair<float, float> > legacy_prune_range;\n','')
    a = selector.index('        auto old_conditions =')
    z = selector.index('        std::pair<float, float> tmp_prune_range;', a)
    selector = selector[:a] + selector[z:]
    a = selector.index('      auto old_union =')
    z = selector.index('      if (use_size >= threshold)', a)
    selector = selector[:a] + selector[z:]
    selector = selector.replace('hvs_pruning::solve_record', 'solve_interval')
    # Replace exactly the two pair-vector distance expressions. The provider
    # returns the same rooted distances; it owns exact/PQ approximation policy.
    for space, field in [('e','first'), ('s','second')]:
        a = selector.index('        float xq_'+space+'_dist = hvs_metric_distance(')
        z = selector.index(';', a)+1
        selector = selector[:a] + ('        float xq_'+space+'_dist = distance(id, candidate[i].id).'+field+';') + selector[z:]
    assert '_data1' not in selector and '_data2' not in selector and '_distance->' not in selector
    assert 'parameter' not in selector and 'hvs_pruning' not in selector and 'legacy' not in selector
    helpers = [
        ('void findSkyline(std::vector<NeighborH> &points, std::vector<NeighborH> &skyline, std::vector<NeighborH> &remain_points)', 'void findSkyline('),
        ('void intersection(const std::vector<std::pair<float,float>> &picked_available_range, const std::pair<float,float> &use_range, std::vector<std::pair<float,float>> &shared_use_range)', '::intersection('),
        ('void get_use_range(std::vector<std::pair<float,float>> &prune_range, std::vector<std::pair<float,float>> &after_pruned_use_range)', '::get_use_range('),
        ('std::vector<std::pair<float,float>> mergeIntervals(std::vector<std::pair<float,float>> &intervals)', '::mergeIntervals('),
    ]
    semantics = E/'u-shape-20261113/scripts/pruning_semantics.h'
    if not semantics.exists():
        semantics = E/'metric-consistent-20261111/scripts/pruning_semantics.h'
    assert semantics.exists(), 'verified inequality helper missing'
    out = ROOT/'implementation'
    (out/'pruning_semantics.h').write_bytes(semantics.read_bytes())
    code = '''// Generated by extract_prune.py from pinned, independently validated B.
#include "deg_prune.h"
#include "pruning_semantics.h"
#include <algorithm>
#include <cmath>
#include <limits>
#include <stdexcept>
#include <unordered_set>
namespace hvs_update {
namespace {
using pipeann::NeighborH;
using pipeann::DEGNeighbor;
std::pair<float,float> solve_interval(float slope, float rhs) {
  auto now = pruning_semantics::solve(slope, rhs);
  return now.empty() ? std::make_pair(0.f, 0.f)
                    : std::make_pair(float(now.lo), float(now.hi));
}
'''
    for declaration, needle in helpers:
        code += declaration + ' ' + body(text, needle) + '\n'
    code += '''}
std::vector<pipeann::DEGNeighbor> prune_detailed(
    std::vector<pipeann::NeighborH> pool, unsigned range,
    const PairDistance &distance) {
  std::vector<pipeann::DEGNeighbor> pruned_list;
  auto select = [&]() ''' + selector + ''';
  select();
  return pruned_list;
}
std::vector<uint32_t> prune(std::vector<pipeann::NeighborH> pool,
                           unsigned degree, const PairDistance &distance) {
  auto selected = prune_detailed(std::move(pool), degree, distance);
  std::vector<uint32_t> ids;
  std::unordered_set<uint32_t> seen;
  for (const auto &v : selected) {
    if (!seen.insert(v.id_).second)
      throw std::runtime_error("duplicate DEG output");
    ids.push_back(v.id_);
  }
  if (ids.size() > degree) throw std::runtime_error("DEG degree overflow");
  return ids;
}
}
'''
    (out/'deg_prune.cpp').write_text(code, encoding='utf-8')
    (ROOT/'analysis').mkdir(exist_ok=True)
    (ROOT/'analysis/prune-provenance.json').write_text(json.dumps(dict(
        verified_source=str(source), verified_source_sha256=sha(raw),
        original_formal_source_sha256=proof['formal_source'],
        function_gate=str(AB/'function-v2/validation/function-gate.json'),
        helpers_source=str(semantics), helpers_sha256=sha(semantics.read_bytes()),
        extracted_source_sha256=sha(code.encode()),
        transformations=['remove legacy-only telemetry', 'inject pair-distance provider instead of global vector arrays',
                         'pass degree directly', 'unchanged skyline/interval helper bodies'],
        semantic_replay='required before engine use'),indent=2)+'\n')


if __name__ == '__main__':
    main()
